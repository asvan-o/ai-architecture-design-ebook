/** @param {string} text @returns {string} */
export function ebookText(text) {
  return text
    .replaceAll('수강생용 결과는', '분석 결과는')
    .replaceAll('수강생이 정한 우선순위를', '직접 정한 우선순위를')
    .replaceAll('기존 A/B 강사 예시를', '제공된 A/B 예시를')
    .replaceAll('빠르게 진행한 수강생의 선택 실습', '심화 선택 실습')
    .replaceAll('다른 도면을 선택한 수강생은', '다른 도면을 선택한 경우')
    .replaceAll('수강생이 고르는', '직접 고르는')
    .replaceAll('수강생 실습 기록지', '실습 기록지')
    .replaceAll('수강생 실행 기록 양식', '실행 기록 양식')
    .replaceAll('수강생 실행:', '기본 실습:')
    .replaceAll('수강생 선택 확장:', '선택 확장:')
    .replaceAll('강사 시범 보드', '방향 갱신 보드 예시')
    .replaceAll('강사 시범 · Dark Walnut에서 Natural Oak로', '디자인 방향 확장 · Dark Walnut에서 Natural Oak로')
    .replaceAll('강사 참고 예시', '참고 예시')
    .replaceAll('강사 적용 예시', '적용 예시')
    .replaceAll('강사 연속 예제', '연속 예제')
    .replaceAll('강사 예제', '실습 예제')
    .replaceAll('강사 예시', '적용 예시')
    .replaceAll('강사 시범', '심화 예제')
    .replaceAll('강사 결과', '예시 결과')
    .replaceAll('강사 수정 공간', '수정 공간 예시')
    .replaceAll('강사 대안', '수정 대안')
    .replaceAll('강사 BASE 01', 'BASE 01 예제')
    .replaceAll('강사 대표', '대표 예제')
    .replaceAll('강사 준비', '기준 현장')
    .replaceAll('강사 트랙 A', '예제 A')
    .replaceAll('강사 트랙 B', '예제 B')
    .replaceAll('강사 비교 메모', '비교 메모')
    .replaceAll('강사 시각 검수 노트', '시각 검수 노트')
    .replaceAll('강사 증빙', '생성 기록')
    .replaceAll('강사 참고', '상세 참고')
    .replaceAll('강사 A2', '보완안 A2')
    .replaceAll('강사 A', '예제 A')
    .replaceAll('1교시의', '앞 단계의')
    .replaceAll('1교시는', '앞 단계는')
    .replaceAll('앞 교시', '앞 단계')
    .replaceAll('다음 교시', '다음 단계')
    .replaceAll('이번 교시', '이번 파트')
    .replace(/제?([1-6])교시/g, 'Part $1')
    .replaceAll('독립 Reviewer 검수 및 사용자 최종 승인 대기.', '');
}
